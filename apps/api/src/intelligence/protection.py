"""Overload Protection and Connection Pool Sizing Engine."""
import math
from typing import Any, Dict, Optional
from pydantic import BaseModel, Field


class PoolSizingInput(BaseModel):
    arrival_qps: float = Field(..., ge=1.0, le=100000.0, description="Observed peak query arrival rate (QPS)")
    mean_latency_ms: float = Field(..., ge=0.1, le=60000.0, description="Mean query execution duration in milliseconds")
    cpu_cores: int = Field(default=8, ge=1, le=128, description="Target database CPU core count")
    disk_type: str = Field(default="ssd", description="'ssd' or 'nvme' or 'hdd'")
    max_client_connections: int = Field(default=1000, ge=10, le=10000, description="Client frontend/service connection ceiling")
    reserve_headroom_ratio: float = Field(default=0.25, ge=0.1, le=1.0, description="Safety headroom multiplier (25% default)")


class ProtectionConfigResult(BaseModel):
    littles_law_concurrency: float
    recommended_pool_size: int
    recommended_reserve_pool: int
    max_client_connections: int
    suggested_statement_timeout_ms: int
    suggested_idle_in_tx_timeout_ms: int
    pgbouncer_ini_content: str
    edge_rate_limit_policy: Dict[str, Any]
    formula_explanation: str


class OverloadProtectionEngine:
    """Computes connection pool limits and generates configuration artifacts to safeguard databases."""

    @staticmethod
    def calculate_pool_sizing(inp: PoolSizingInput) -> ProtectionConfigResult:
        # Little's Law: N = lambda * W
        mean_latency_sec = inp.mean_latency_ms / 1000.0
        littles_concurrency = inp.arrival_qps * mean_latency_sec

        # PostgreSQL hardware capability formula: pool = 2 * CPU + spindles
        spindles = 1 if inp.disk_type.lower() in ["ssd", "nvme"] else 4
        hardware_pool = (2 * inp.cpu_cores) + spindles

        # Balanced pool size: scale with Little's Law but capped by physical core saturation
        raw_target = max(littles_concurrency * (1.0 + inp.reserve_headroom_ratio), float(hardware_pool))
        # Clamp between 10 and 120 to prevent postgres connection degradation
        pool_size = max(10, min(120, int(math.ceil(raw_target))))
        reserve_pool = max(2, int(pool_size * 0.2))

        # Statement timeouts: 5x mean latency or minimum 2500ms
        statement_timeout_ms = max(2500, int(inp.mean_latency_ms * 5.0))
        idle_in_tx_timeout_ms = min(15000, max(5000, statement_timeout_ms * 2))

        # Generate PgBouncer INI config
        pgbouncer_ini = f"""; Auto-generated by Trafiora Database Workload Intelligence
; Protection Policy: Little's Law concurrency ({littles_concurrency:.1f}) across {inp.cpu_cores} CPU cores

[databases]
* = host=127.0.0.1 port=5432 auth_user=postgres

[pgbouncer]
logfile = /var/log/pgbouncer/pgbouncer.log
pidfile = /var/run/pgbouncer/pgbouncer.pid
listen_addr = 0.0.0.0
listen_port = 6432
auth_type = scram-sha-256
auth_file = /etc/pgbouncer/userlist.txt

; Connection Pool Sizing
pool_mode = transaction
default_pool_size = {pool_size}
min_pool_size = {max(5, int(pool_size * 0.3))}
reserve_pool_size = {reserve_pool}
reserve_pool_timeout = 5.0
max_client_conn = {inp.max_client_connections}
max_db_connections = {pool_size + reserve_pool + 5}

; Timeouts and Contention Circuit Breakers
server_idle_timeout = 60.0
server_connect_timeout = 5.0
query_timeout = {statement_timeout_ms / 1000.0:.1f}
client_idle_timeout = 120.0
"""

        # Generate Envoy / NGINX Rate Limiting Policy
        rate_limit_policy = {
            "rate_limit_service": "envoy.filters.http.ratelimit",
            "domain": "database_workload_protection",
            "descriptors": [
                {
                    "key": "generic_key",
                    "value": "db_query_ingress",
                    "rate_limit": {
                        "unit": "SECOND",
                        "requests_per_unit": int(inp.arrival_qps * 1.5),
                    },
                }
            ],
            "circuit_breaker": {
                "max_pending_requests": int(inp.arrival_qps * 0.5),
                "max_connections": inp.max_client_connections,
            },
        }

        explanation = (
            f"Based on Little's Law (N = lambda * W = {inp.arrival_qps} QPS * {mean_latency_sec:.4f}s = "
            f"{littles_concurrency:.1f} concurrent active queries) and database host size of {inp.cpu_cores} cores, "
            f"a pool size of {pool_size} (plus {reserve_pool} reserve connections) prevents PostgreSQL process explosion "
            f"while sustaining peak throughput."
        )

        return ProtectionConfigResult(
            littles_law_concurrency=round(littles_concurrency, 2),
            recommended_pool_size=pool_size,
            recommended_reserve_pool=reserve_pool,
            max_client_connections=inp.max_client_connections,
            suggested_statement_timeout_ms=statement_timeout_ms,
            suggested_idle_in_tx_timeout_ms=idle_in_tx_timeout_ms,
            pgbouncer_ini_content=pgbouncer_ini,
            edge_rate_limit_policy=rate_limit_policy,
            formula_explanation=explanation,
        )
